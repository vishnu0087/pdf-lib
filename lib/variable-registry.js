/** Phase 10 — Per-doc-type variable registry.
 *  Defines what inline (scalar chip) and block (region) variables a doc type
 *  exposes. Inline variables include a `resolve(data)` function that returns
 *  the runtime value from a JSON data object. Block variables reference a
 *  renderer key looked up in the BLOCK_RENDERERS dispatch table. */

/** @typedef {{ token: string, label: string, type: string, resolve: (data: any) => string }} InlineVar */
/** @typedef {{ id: string, label: string, description: string, renderer: string }} BlockVar */
/** @typedef {{ inline: InlineVar[], blocks: BlockVar[] }} DocTypeRegistry */

function pickP1Block(data, id) {
  const blocks = data?.page1?.blocks;
  if (!Array.isArray(blocks)) return null;
  return blocks.find((b) => b && b.id === id) || null;
}

function pickP1Column(data, blockId, columnId) {
  const block = pickP1Block(data, blockId);
  const cols = block?.columns;
  if (!Array.isArray(cols)) return null;
  return cols.find((c) => c && c.id === columnId) || null;
}

function pickStackItem(stackBlock, index) {
  const items = stackBlock?.items;
  if (!Array.isArray(items)) return null;
  return items[index] || null;
}

/** @type {Record<string, DocTypeRegistry>} */
export const VARIABLE_REGISTRY = {
  quote: {
    /* Phase 10b: inline chip tokens come from the runtime tokenMap (auto-
       generated by clonePlaceholderPayload from fixture data), so the
       registry's inline list stays empty. Special tokens with custom
       semantics (e.g. LETTER_BODY → multi-paragraph HTML) are handled
       directly in the resolver instead of via a registry entry. */
    inline: [],
    blocks: [
      {
        id: 'letter_body',
        label: 'Letter Body',
        description: 'Salutation + intro paragraphs',
        renderer: 'renderLetterBodyBlock',
      },
      {
        id: 'line_items',
        label: 'Line Items Table',
        description: 'Product / service items with totals',
        renderer: 'renderLineItemsBlock',
      },
    ],
  },
  /* Phase 11+: invoice, salary, sales — populate alongside their renderers. */
  invoice: { inline: [], blocks: [] },
  salary:  { inline: [], blocks: [] },
  sales:   { inline: [], blocks: [] },
};

/** Resolve a single inline variable's runtime value. Returns empty string
 *  when the registry entry, doc-type, or runtime data is missing. */
export function resolveInlineVariableValue(docType, token, data) {
  const reg = VARIABLE_REGISTRY[docType];
  if (!reg) return '';
  const v = reg.inline.find((x) => x.token === token);
  if (!v) return '';
  try {
    const out = v.resolve(data);
    return out == null ? '' : String(out);
  } catch {
    return '';
  }
}

/** Look up a block-variable's renderer key. */
export function getBlockRendererKey(docType, blockId) {
  const reg = VARIABLE_REGISTRY[docType];
  if (!reg) return null;
  const b = reg.blocks.find((x) => x.id === blockId);
  return b ? b.renderer : null;
}
